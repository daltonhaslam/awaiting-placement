// Bundle JS, inline CSS + data, write ../docs/index.html (one self-contained page).
// Env: AP_DATA  data file (default src/data/ap.json, produced by the pipeline);
//      BUILD_OUT_DIR  write index.html there instead of ../docs (tests).
// Only a build with neither set updates vercel.json's CSP hashes.
import { build, transform } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { escapeInlineScript, cspHash, withScriptHashes } from './inline-script.mjs';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';
import { SITE, THEME_KEY, PUBLISHED } from './src/js/site.js';
import { SECTIONS, parseHash, bootPage } from './src/js/router.js';
import { cardImageUrl, cardNumbers, cssColor, iconSvg } from './og-card.mjs';
import { prerender } from './prerender.mjs';

const here = (p) => new URL(p, import.meta.url);
const read = (p) => readFileSync(here(p), 'utf8');

const dataPath = process.env.AP_DATA ? resolve(process.env.AP_DATA) : fileURLToPath(here('src/data/ap.json'));
if (!existsSync(dataPath)) {
  console.error(`Data file not found: ${dataPath}\nRun the pipeline (python3 -I pipeline/build_data.py) to produce web/src/data/ap.json, or set AP_DATA=<path>.`);
  process.exit(1);
}
const rawData = readFileSync(dataPath, 'utf8');
const parsed = JSON.parse(rawData);
const { latestFy, nClean } = parsed.meta;

// The explicit night-mode toggle reuses the dark media block's tokens verbatim.
const tokens = read('src/styles/tokens.css');
const darkDecls = /:root:not\(\[data-theme="light"\]\)\s*\{([^}]*)\}/.exec(tokens)?.[1];
if (!darkDecls) throw new Error('tokens.css: dark media block not found');
// fonts.css (generated by fonts.mjs) points the @font-face rules at docs/fonts/, served from the page's own origin.
const fontsCss = read('src/styles/fonts.css');
// The two faces the first screen sets (the headline and the body text) start loading before the CSS is parsed.
const PRELOAD = ['big-shoulders-display', 'overpass'].map((f) => {
  const href = new RegExp(`url\\((fonts/${f}\\.[0-9a-f]+\\.woff2)\\)`).exec(fontsCss)?.[1];
  if (!href) throw new Error(`fonts.css: no ${f} file`);
  return `<link rel="preload" href="${href}" as="font" type="font/woff2" crossorigin>`;
}).join('');
// Print: every token the dark theme overrides gets its light value back (the first definition in tokens.css is the light
// one), at a specificity both dark selectors lose to, so Night mode never prints light ink on white paper.
const lightForPrint = darkDecls.match(/--[\w-]+(?=:)/g).map((k) => {
  const v = new RegExp(`${k}:\\s*([^;]+);`).exec(tokens)?.[1];
  if (!v) throw new Error(`tokens.css: ${k} has no light value`);
  return `${k}: ${v};`;
}).join(' ');
const css = (await transform([fontsCss, tokens, `:root[data-theme="dark"] {${darkDecls}}`, `@media print { :root:root:root { ${lightForPrint} } }`,
  ...['base', 'components', 'charts', 'print'].map((n) => read(`src/styles/${n}.css`))].join('\n'),
  { loader: 'css', minify: true })).code;
const js = (await build({ entryPoints: [fileURLToPath(here('src/js/main.js'))], bundle: true, format: 'iife',
  minify: true, write: false, target: 'es2020', legalComments: 'none' })).outputFiles[0].text;
// Escape every '<' so no data string can close the script element.
const data = rawData.replace(/</g, '\\u003c');

// Attribute values in the head: a quote or angle bracket in the copy must not end the attribute or the tag.
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
// Under 160 characters, so search results and link previews show it whole.
const DESC = `Medicare Advantage patients stay longer in the hospital before post-acute care. What those days mean for beds. `
  + `Profiles of ${nClean.toLocaleString('en-US')} hospitals, FY${latestFy} cost reports.`;
if (DESC.length > 160) throw new Error(`meta description is ${DESC.length} characters; keep it under 160`);
const cardN = cardNumbers(parsed);
// The SVG icon for browsers that take one; favicon.ico (Safari, and the browser's own /favicon.ico request) and the
// Apple touch icon are the same mark rendered by icons.mjs.
const ICON = `<link rel="icon" href="favicon.ico" sizes="32x32"><link rel="icon" type="image/svg+xml" href="data:image/svg+xml,${encodeURIComponent(iconSvg(parsed))}">`
  + '<link rel="apple-touch-icon" href="apple-touch-icon.png">';
const OG_ALT = `Awaiting Placement: Ready to leave the hospital. Still waiting for the next bed. Now serving ${cardN.now}, your number ${cardN.you}: average days in hospital before inpatient rehab, traditional Medicare vs Medicare Advantage.`;
const OG = `<meta property="og:image" content="${cardImageUrl(readFileSync(here('../docs/og.png')))}"><meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">`
  + `<meta property="og:image:alt" content="${attr(OG_ALT)}"><meta name="twitter:card" content="summary_large_image"><meta name="twitter:image:alt" content="${attr(OG_ALT)}">`;
const CANON = new URL(SITE.url).href;
// Light and dark page colours read from tokens.css (the first --page is the light one), so the browser chrome on phones
// matches the page and cannot drift from it.
const THEME_COLOR = `<meta name="theme-color" content="${cssColor(tokens, 'page')}" media="(prefers-color-scheme: light)">`
  + `<meta name="theme-color" content="${cssColor(darkDecls, 'page')}" media="(prefers-color-scheme: dark)">`;
const title = `${SITE.name}: Medicare Advantage and hospital length of stay`;
// Before first paint: apply a saved Day/Night choice (no flash) and name the
// route in data-boot so the boot CSS shows the pre-rendered page the app will render ("home" for the story page and
// its sections, "methods", else "other", which shows "Loading…"). The route comes from router.parseHash and bootPage
// themselves, inlined with the one module binding they read (SECTIONS); router.js keeps them ES5. Each part has its own
// try/catch, so a failure in the route code cannot take the theme with it. Inline scripts are allowed by
// their sha256 in the CSP (see below), not by 'unsafe-inline'.
const HEAD_JS = `try{var t=localStorage.getItem(${JSON.stringify(THEME_KEY)});`
  + `if(t==='dark'||t==='light')document.documentElement.setAttribute('data-theme',t)}catch(e){}`
  + `try{var SECTIONS=${JSON.stringify(SECTIONS)};var parseHash=${parseHash.toString()};var bootPage=${bootPage.toString()};`
  + `document.documentElement.setAttribute('data-boot',bootPage(parseHash(location.hash).view))}catch(e){}`;
const HEAD = `<script>${HEAD_JS}</script>`;
const APP_JS = escapeInlineScript(js);

// The story page and Methods, rendered from the same data, in place of the shell's placeholders.
const pre = await prerender(parsed, { published: PUBLISHED, origin: SITE.url });
const fill = (html, name, markup) => {
  const mark = `<!--prerender:${name}-->`;
  if (!html.includes(mark)) throw new Error(`shell.html: ${mark} not found`);
  return html.replace(mark, () => markup);
};
const body = fill(fill(read('src/shell.html'), 'main', pre.main), 'footer', pre.footer);
const doc = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">`
  + `<title>${attr(title)}</title><meta name="description" content="${attr(DESC)}"><link rel="canonical" href="${CANON}">${THEME_COLOR}`
  + `<meta property="og:title" content="${attr(title)}"><meta property="og:description" content="${attr(DESC)}"><meta property="og:type" content="website"><meta property="og:url" content="${CANON}">`
  + `<meta property="og:site_name" content="${attr(SITE.name)}"><meta property="og:locale" content="en_US">${OG}`
  + `${HEAD}${ICON}${PRELOAD}<style>${css}</style></head><body>${body}`
  + `<script id="ap-data" type="application/json">${data}</script><script>${APP_JS}</script></body></html>`;

// Pin the CSP's script-src to exactly these two inline scripts. Only the real build (default data, default output) may
// rewrite the tracked vercel.json; fixture/test builds must never touch tracked files, or vercel.json desyncs from docs/.
if (!process.env.BUILD_OUT_DIR && !process.env.AP_DATA) {
  const vercelPath = fileURLToPath(here('../vercel.json'));
  const vercel = readFileSync(vercelPath, 'utf8');
  const csp = withScriptHashes(/"Content-Security-Policy",\s*"value": "([^"]*)"/.exec(vercel)[1], [cspHash(HEAD_JS), cspHash(APP_JS)]);
  writeFileSync(vercelPath, vercel.replace(/("Content-Security-Policy",\s*"value": ")[^"]*"/, `$1${csp}"`));
}

const outDir = process.env.BUILD_OUT_DIR ?? fileURLToPath(here('../docs/'));
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'index.html'), doc);
const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
console.log(`${join(outDir, 'index.html')} ${kb(doc)} (js ${kb(js)}, css ${kb(css)}, data ${kb(data)}, pre-rendered ${kb(pre.main + pre.footer)})`);
